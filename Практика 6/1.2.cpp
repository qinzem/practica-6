#include <iostream>      // Подключаем библиотеку ввода-вывода
using namespace std;     // Используем стандартное пространство имен

int main() {             // Начало программы
    int n;               // Переменная для размера
    cin >> n;            // Читаем размер

    for (int i = 0; i < n; i++) {           // Внешний цикл: проходим по каждой строке (i - номер строки)
        
        // Печатаем нули. С каждой новой строкой их становится на 1 меньше
        for (int j = 0; j < n - 1 - i; j++) { 
            cout << 0 << " ";               // Печатаем 0 и пробел
        }
        
        cout << 1 << " ";                   // Всегда печатаем ровно одну единицу (угол)
        
        // Печатаем двойки. С каждой новой строкой их становится на 1 больше
        for (int j = 0; j < i; j++) {       
            cout << 2 << " ";               // Печатаем 2 и пробел
        }
        
        cout << endl;                       // Заканчиваем строку, переходим на новую
    }
    return 0;                               // Завершаем программу
}
