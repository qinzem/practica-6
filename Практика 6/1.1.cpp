#include <iostream>      // Подключаем библиотеку для ввода и вывода (cin, cout)
using namespace std;     // Чтобы не писать std:: перед каждым cin и cout

int main() {             // Главная функция, с которой начинается программа
    int n;               // Объявляем переменную n для хранения размера квадрата
    cin >> n;            // Считываем размер квадрата с клавиатуры

    for (int i = 0; i < n; i++) {       // Внешний цикл: перебираем строки (от 0 до n-1)
        for (int j = 0; j < n; j++) {   // Внутренний цикл: перебираем столбцы (от 0 до n-1)
            
            // Проверяем, находится ли клетка на побочной диагонали
            if (i + j == n - 1) {       
                cout << 1 << " ";       // Если да, печатаем 1 и пробел
            } 
            // Проверяем, находится ли клетка выше диагонали
            else if (i + j < n - 1) {   
                cout << 0 << " ";       // Если да, печатаем 0 и пробел
            } 
            // Если не подошло ни одно условие, значит клетка ниже диагонали
            else {                      
                cout << 2 << " ";       // Печатаем 2 и пробел
            }
        }
        cout << endl;                   // Когда строка закончилась, переходим на новую
    }
    return 0;                           // Сообщаем, что программа завершилась без ошибок
}