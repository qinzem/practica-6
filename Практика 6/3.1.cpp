#include <iostream>              // Подключаем библиотеку, чтобы работали ввод (cin) и вывод (cout)
#include <string>                // Подключаем библиотеку, чтобы работать с текстом (строками)
using namespace std;             // Пишем это, чтобы не писать слово std:: перед каждым cin и cout

int main() {                     // Главная функция. С нее начинается выполнение программы
    string s;                    // Создаем переменную s (это будет строка, наше первое число)
    int n;                       // Создаем переменную n (это будет целое число, сколько раз повторять)
    cin >> s >> n;               // Читаем с клавиатуры сначала строку, потом число, и кладем их в переменные

    for (int step = 1; step < n; step++) { // Запускаем цикл. Он сработает N-1 раз (первая строка уже есть)
        
        string next = "";        // Создаем пустую строку next. Сюда будем собирать новый результат
        char tekushaya = s[0];   // Берем самый первый символ из строки s и запоминаем его (это наша текущая цифра)
        int count = 1;           // Создаем счетчик. Раз мы взяли одну цифру, счетчик равен 1

        for (int i = 1; i < s.length(); i++) { // Запускаем цикл по всем остальным символам (начиная со второго)
            
            if (s[i] == tekushaya) { // Если текущий символ строки такой же, как запомненный ранее...
                count++;             // ...то просто увеличиваем счетчик на 1
            } else {                 // Если символы РАЗНЫЕ (значит, серия одинаковых цифр закончилась)...
                
                // В новую строку склеиваем: число (сколько насчитали) и саму цифру. 
                // to_string(count) превращает число в текст, чтобы его можно было склеить.
                next = next + to_string(count) + tekushaya; 
                
                tekushaya = s[i];    // Запоминаем новую цифру, которую встретили
                count = 1;           // Сбрасываем счетчик на 1 (новая цифра уже встретилась 1 раз)
            }
        }                        // Конец внутреннего цикла (прошли по всей строке)

        // ВАЖНО: после цикла мы не записали самую последнюю группу цифр, поэтому дописываем её сейчас
        next = next + to_string(count) + tekushaya; 
        
        s = next;                // Заменяем старую строку на новую (то, что мы только что насчитали)
    }                            // Конец внешнего цикла (по шагам)

    cout << s << endl;           // Выводим итоговую строку на экран
    return 0;                    // Сообщаем, что программа успешно завершилась
}                                // Конец главной функции
